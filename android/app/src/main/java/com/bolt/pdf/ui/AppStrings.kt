const val SYSTEM_LANGUAGE_TAG = ""

data class AppLocaleOption(
    val tag: String,
    val displayName: String
)

fun supportedLocaleOptions(systemDefaultLabel: String): List<AppLocaleOption> {
    val options = mutableListOf(
        AppLocaleOption(tag = SYSTEM_LANGUAGE_TAG, displayName = systemDefaultLabel)
    )
    BuildConfig.SUPPORTED_LOCALES.forEach { tag ->
        val locale = Locale.forLanguageTag(tag)
        val nativeName = locale.getDisplayName(locale)
            .replaceFirstChar { ch ->
                if (ch.isLowerCase()) ch.titlecase(locale) else ch.toString()
            }
            .ifBlank { tag }
        options += AppLocaleOption(tag = tag, displayName = nativeName)
    }
    return options
}

fun resolveLocale(languageTag: String): Locale {
    return if (languageTag.isBlank()) {
        Locale.getDefault()
    } else {
        Locale.forLanguageTag(languageTag)
    }
}

fun layoutDirectionFor(locale: Locale): LayoutDirection {
    return if (TextUtils.getLayoutDirectionFromLocale(locale) == View.LAYOUT_DIRECTION_RTL) {
        LayoutDirection.Rtl
    } else {
        LayoutDirection.Ltr
    }
}

fun createLocalizedContext(base: Context, languageTag: String): Context {
    if (languageTag.isBlank()) return base
    val locale = Locale.forLanguageTag(languageTag)
    val config = Configuration(base.resources.configuration).apply {
        setLocale(locale)
        setLocales(LocaleList(locale))
        setLayoutDirection(locale)
    }
    return base.createConfigurationContext(config)
}

